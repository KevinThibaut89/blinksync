"""Generate go2rtc.yaml from the saved accounts and restart go2rtc."""

from __future__ import annotations

import base64
import json
import logging
from dataclasses import dataclass
from pathlib import Path

from aiohttp import (
    ClientError,
    ClientSession,
    ClientTimeout,
    ServerDisconnectedError,
)

from .accounts import AccountStore, slugify
from .settings import Settings, blinksync_bin, data_dir, write_private

_LOGGER = logging.getLogger(__name__)


@dataclass(frozen=True)
class StreamEntry:
    name: str
    account: str
    camera: dict


def stream_entries(store: AccountStore) -> list[StreamEntry]:
    """One go2rtc stream per camera, named after the camera.

    The account name is only prefixed when two accounts have a camera with the
    same name, so URLs stay short for the common single-account setup.
    """
    cameras = [(acct, cam) for acct in store.names() for cam in store.cameras(acct)]
    counts: dict[str, int] = {}
    for _, cam in cameras:
        slug = slugify(cam["name"])
        counts[slug] = counts.get(slug, 0) + 1

    entries, used = [], set()
    for acct, cam in cameras:
        name = slugify(cam["name"])
        if counts[name] > 1:
            name = f"{slugify(acct)}_{name}"
        if name in used:
            name = f"{name}_{cam['id']}"
        used.add(name)
        entries.append(StreamEntry(name, acct, cam))
    return entries


def _q(value) -> str:
    # JSON strings are valid YAML scalars and handle all quoting for us.
    return json.dumps(value)


def render_config(entries: list[StreamEntry], settings: Settings, binary: str) -> str:
    lines = [
        "# Generated by blinksync. Edit settings.json or use the web UI instead;",
        "# this file is overwritten whenever accounts or cameras change.",
        "api:",
        f'  listen: ":{settings.go2rtc_port}"',
        f"  username: {_q(settings.web_username)}",
        f"  password: {_q(settings.web_password)}",
        "rtsp:",
        f'  listen: ":{settings.rtsp_port}"',
    ]
    if settings.rtsp_username:
        lines += [
            f"  username: {_q(settings.rtsp_username)}",
            f"  password: {_q(settings.rtsp_password)}",
        ]
    lines += [
        "webrtc:",
        f'  listen: ":{settings.webrtc_port}"',
        "exec:",
        "  # Only our own streamer may be run by exec: sources.",
        f"  allow_paths: [{_q(binary)}]",
        "log:",
        "  format: text",
        "  # go2rtc only logs exec stderr (the streamer's messages) at debug.",
        "  exec: debug",
        "streams:",
    ]
    if not entries:
        lines[-1] = "streams: {}"
    for entry in entries:
        source = (
            f"exec:{binary} stream {entry.account} {entry.camera['id']}"
            f" --max-minutes {settings.max_minutes}"
            "#killsignal=15#killtimeout=10"
        )
        lines.append(f"  {entry.name}: {_q(source)}  # {entry.camera['name']}")
    return "\n".join(lines) + "\n"


def config_path() -> Path:
    return data_dir() / "go2rtc.yaml"


def write_config(store: AccountStore, settings: Settings) -> bool:
    """Write go2rtc.yaml. Returns True if the content changed."""
    text = render_config(stream_entries(store), settings, blinksync_bin())
    path = config_path()
    if path.exists() and path.read_text() == text:
        return False
    write_private(path, text)
    return True


def basic_auth(username: str, password: str) -> str:
    token = base64.b64encode(f"{username}:{password}".encode()).decode()
    return f"Basic {token}"


def api_headers(settings: Settings) -> dict:
    """go2rtc's API shares the web UI's username and password."""
    return {"Authorization": basic_auth(settings.web_username, settings.web_password)}


async def restart(settings: Settings) -> bool:
    """Ask the running go2rtc to re-exec itself so it reloads go2rtc.yaml."""
    try:
        async with ClientSession(timeout=ClientTimeout(total=5)) as session:
            async with session.post(
                f"{settings.go2rtc_api}/api/restart", headers=api_headers(settings)
            ) as r:
                if r.status >= 400:
                    _LOGGER.warning("go2rtc restart returned HTTP %s", r.status)
                    return False
    except ServerDisconnectedError:
        pass  # go2rtc re-exec'd before finishing the response: that's success
    except (ClientError, TimeoutError) as err:
        _LOGGER.warning("Could not reach go2rtc to restart it: %s", err)
        return False
    return True


async def apply(store: AccountStore, settings: Settings) -> bool:
    """Regenerate the config and restart go2rtc if it changed."""
    if write_config(store, settings):
        return await restart(settings)
    return True
